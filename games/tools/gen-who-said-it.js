/* Generate js/data-who-said-it.js from the verified 500-quote bank.
   Run: node tools/gen-who-said-it.js  (from the verse-games folder)

   The bank (../who-said-it-levels/quote-bank-500.json) holds 10 levels x 50
   entries, every quote text verified word for word against KJV. This script
   NEVER rewords quotes; it only picks 4 same-level distractor speakers per
   question (same era preferred) and shuffles the 5 options with a seeded
   PRNG, so every build is byte-identical. Do not hand-edit the output;
   regenerate. */
const fs = require('fs');
const path = require('path');
const base = path.join(__dirname, '..');
const bank = JSON.parse(fs.readFileSync(
  path.join(base, '..', 'who-said-it-levels', 'quote-bank-500.json'), 'utf8'));

function hash32(s){
  let h = 2166136261;
  for(let i = 0; i < s.length; i++){ h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}
function mulberry32(seed){
  let a = seed >>> 0;
  return function(){
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const LEVEL_NAMES = {
  1:'Famous Voices', 2:'Familiar Voices', 3:'Tested Voices', 4:'Searching Voices',
  5:'Proving Voices', 6:'Hidden Voices', 7:'Quiet Voices', 8:'Distant Voices',
  9:'Rare Voices', 10:'The Faintest Voices'
};

const levels = [];
for(let L = 1; L <= 10; L++){
  const entries = bank.levels[String(L)];
  if(!entries || entries.length !== 50)
    throw new Error('level ' + L + ' must hold exactly 50 entries');
  const speakers = [...new Set(entries.map(e => e.speaker))];
  if(speakers.length < 5)
    throw new Error('level ' + L + ' needs at least 5 distinct speakers');
  const questions = entries.map((e, i) => {
    if(!e.ref || !e.speaker || !e.quote)
      throw new Error('level ' + L + ' q' + i + ' missing ref/speaker/quote');
    if(/[\u2013\u2014]/.test(e.quote))
      throw new Error('em/en dash in quote ' + e.ref);
    if(/<\/script/i.test(e.quote))
      throw new Error('script tag in quote ' + e.ref);
    const rng = mulberry32(hash32('wsi:' + L + ':' + i));
    const sameEra = speakers.filter(s =>
      s !== e.speaker && entries.some(x => x.speaker === s && x.era === e.era));
    const otherEra = speakers.filter(s =>
      s !== e.speaker && sameEra.indexOf(s) === -1);
    const pool = sameEra.concat(otherEra);
    for(let k = pool.length - 1; k > 0; k--){
      const j = Math.floor(rng() * (k + 1));
      const t = pool[k]; pool[k] = pool[j]; pool[j] = t;
    }
    const distractors = pool.slice(0, 4);
    if(distractors.length < 4)
      throw new Error('not enough distractors, level ' + L + ' q' + i);
    const options = [e.speaker].concat(distractors);
    for(let k = options.length - 1; k > 0; k--){
      const j = Math.floor(rng() * (k + 1));
      const t = options[k]; options[k] = options[j]; options[j] = t;
    }
    if(new Set(options).size !== 5)
      throw new Error('duplicate options, level ' + L + ' q' + i);
    return {q:e.quote, options:options, a:options.indexOf(e.speaker), ref:e.ref};
  });
  levels.push({name:LEVEL_NAMES[L], questions:questions});
}

const out =
'/* Who Said It: 500-voice campaign data. Generated by tools/gen-who-said-it.js\n' +
'   from the verified quote bank (quotes never reworded). Do not hand-edit. */\n' +
'VG.register({\n' +
'id:"who-said-it",\n' +
'title:"Who Said It",\n' +
'kicker:"KJV \\u00b7 59 books",\n' +
'source:"Genesis to Revelation",\n' +
'desc:"Five hundred voices from Genesis to Revelation. Hear the words, name the speaker, and climb ten levels from the famous to the deeply obscure.",\n' +
'meta:"10 levels \\u00b7 500 quotes \\u00b7 rounds of five",\n' +
'shelf:"mix",\n' +
'mode:"whosaidit",\n' +
'playable:true,\n' +
'art:"img/card-wisdom.webp",\n' +
'levels:' + JSON.stringify(levels) + '\n' +
'});\n';

const dest = path.join(base, 'js', 'data-who-said-it.js');
fs.writeFileSync(dest, out);
const nq = levels.reduce((n, l) => n + l.questions.length, 0);
console.log('wrote js/data-who-said-it.js', out.length, 'bytes,', nq, 'questions');
